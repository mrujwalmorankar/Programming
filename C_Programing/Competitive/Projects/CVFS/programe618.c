 void  CREATEDILB()
 {
 
    int i = 0;

    PINODE newn = NULL;
    PINODE temp = NULL;

    temp=head;

    for(i = 1; i <= MAXINODE; i++)
    {
           newn=(PINODE)malloc(sizeof(INODE));
         
           newn->InodeNumber=i;

           if(temp==NULL)
           {
              head = newn;
              temp = head;


           }
           else
           {
              temp -> next = newn;
              temp = temp -> next;
           }

    }
     printf("Marvellous CVFS : DILB gets Created Successfully\n");

 }
 
